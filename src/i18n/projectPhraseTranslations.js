const reverseTranslations = Object.fromEntries(
  Object.entries(projectPhraseTranslations).map(([key, value]) => [normalizeProjectPhrase(value), key])
);

export function normalizeProjectPhrase(value) {
  return String(value)
    .replace(/[’`´]/g, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

export function translateProjectPhrase(value, language) {
  const normalizedValue = normalizeProjectPhrase(value);

  if (!normalizedValue) {
    return value;
  }

  if (language === 'zh') {
    return normalizedTranslations[normalizedValue] ?? value;
  }

  return reverseTranslations[normalizedValue] ?? value;
}
